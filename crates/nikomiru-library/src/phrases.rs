//! Independent local phrase records (PHR-001…PHR-003); never writes word-status or review tables.
use crate::{Library, LibraryError, db::db_err, words::WordStatus};
use redb::{ReadableTable, TableDefinition};
use serde::{Deserialize, Serialize};
const PHRASES: TableDefinition<&str, &[u8]> = TableDefinition::new("phrases");
/// Maximum retained phrase records.
pub const MAX_RECORDS: usize = 10000;
/// Combined field-text budget.
pub const MAX_BYTES: usize = 32 << 20;
/// A frozen original reader or caption location. No absolute file path is stored.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Source {
    /// True for a Books source; false for a video scene.
    pub book: bool,
    /// Library identity.
    pub uid: String,
    /// Human-readable original title.
    pub title: String,
    /// Original book chapter.
    pub chapter: u32,
    /// Original paragraph.
    pub paragraph: u32,
    /// Original UTF-8 byte offset.
    pub offset: u32,
    /// Effective video start; zero for books.
    pub start_ms: u32,
    /// Effective video end; zero for books.
    pub end_ms: u32,
}
/// A phrase's own meaning, learning state and original context.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Phrase {
    /// Stable UUID generated by the application.
    pub id: String,
    /// Study language, independent of UI language.
    pub language: String,
    /// Exact phrase selected or explicitly entered.
    pub text: String,
    /// User's meaning/definition.
    pub definition: String,
    /// Frozen source sentence, or an explicitly entered context.
    pub context: String,
    /// Independent learning state.
    pub status: WordStatus,
    /// Optional source location.
    pub source: Option<Source>,
    /// Creation time, Unix ms.
    pub created_ms: i64,
    /// Last edit time, Unix ms.
    pub changed_ms: i64,
}
fn text_valid(text: &str, limit: usize, multiline: bool) -> bool {
    text.len() <= limit
        && !text
            .chars()
            .any(|c| c.is_control() && (!multiline || !matches!(c, '\n' | '\r' | '\t')))
}
impl Phrase {
    /// Validate bounds and the selected phrase's literal context before any write.
    pub fn valid(&self) -> bool {
        let id = self.id.as_bytes();
        let uuid = id.len() == 36
            && id.iter().enumerate().all(|(i, c)| {
                if [8, 13, 18, 23].contains(&i) {
                    *c == b'-'
                } else {
                    c.is_ascii_hexdigit()
                }
            });
        uuid && !self.text.trim().is_empty()
            && text_valid(&self.text, 4096, false)
            && text_valid(&self.definition, 4096, true)
            && text_valid(&self.context, 16384, true)
            && (self.context.is_empty() || self.context.contains(&self.text))
            && !self.language.is_empty()
            && self.language.len() <= 35
            && self
                .language
                .bytes()
                .all(|c| c.is_ascii_alphanumeric() || c == b'-')
            && self.created_ms >= 0
            && self.changed_ms >= self.created_ms
            && self.source.as_ref().is_none_or(|s| {
                !s.uid.is_empty()
                    && text_valid(&s.uid, 1024, false)
                    && text_valid(&s.title, 1024, false)
                    && s.start_ms <= s.end_ms
                    && s.end_ms <= i32::MAX as u32
                    && if s.book {
                        s.start_ms == 0 && s.end_ms == 0
                    } else {
                        s.end_ms > s.start_ms
                    }
            })
    }
    fn bytes(&self) -> usize {
        self.text.len()
            + self.definition.len()
            + self.context.len()
            + self.language.len()
            + self
                .source
                .as_ref()
                .map_or(0, |s| s.uid.len() + s.title.len())
    }
    fn duplicates(&self, other: &Self) -> bool {
        self.language == other.language
            && self.text == other.text
            && self.context == other.context
            && self.source.as_ref().map(|s| {
                (
                    &s.uid,
                    s.book,
                    s.chapter,
                    s.paragraph,
                    s.offset,
                    s.start_ms,
                    s.end_ms,
                )
            }) == other.source.as_ref().map(|s| {
                (
                    &s.uid,
                    s.book,
                    s.chapter,
                    s.paragraph,
                    s.offset,
                    s.start_ms,
                    s.end_ms,
                )
            })
    }
}
impl Library {
    /// Local phrases, newest edits first; absent additive tables are empty.
    pub fn phrases(&self) -> Result<Vec<Phrase>, LibraryError> {
        self.read(|tx| {
            let table = match tx.open_table(PHRASES) {
                Ok(t) => t,
                Err(redb::TableError::TableDoesNotExist(_)) => return Ok(Vec::new()),
                Err(e) => return Err(LibraryError::Db(e.into())),
            };
            let mut rows = Vec::new();
            let mut bytes = 0usize;
            for row in db_err!(table.iter())? {
                let (_, value) = db_err!(row)?;
                let p: Phrase = postcard::from_bytes(value.value())?;
                bytes += p.bytes();
                if !p.valid() || rows.len() >= MAX_RECORDS || bytes > MAX_BYTES {
                    return Err(LibraryError::Record(postcard::Error::SerdeDeCustom));
                }
                rows.push(p);
            }
            rows.sort_by(|a, b| (b.changed_ms, &b.id).cmp(&(a.changed_ms, &a.id)));
            Ok(rows)
        })
    }
    /// Atomically save one validated phrase, refusing duplicates and dataset overflow.
    pub fn put_phrase(&self, phrase: &Phrase) -> Result<bool, LibraryError> {
        if !phrase.valid() {
            return Ok(false);
        }
        let tx = self.write()?;
        {
            let mut table = db_err!(tx.open_table(PHRASES))?;
            let mut count = 0usize;
            let mut bytes = phrase.bytes();
            for row in db_err!(table.iter())? {
                let (key, value) = db_err!(row)?;
                if key.value() == phrase.id {
                    continue;
                }
                let other: Phrase = postcard::from_bytes(value.value())?;
                if other.duplicates(phrase) {
                    return Ok(false);
                }
                count += 1;
                bytes = bytes.saturating_add(other.bytes());
            }
            if count >= MAX_RECORDS || bytes > MAX_BYTES {
                return Ok(false);
            }
            let data = postcard::to_stdvec(phrase)?;
            db_err!(table.insert(phrase.id.as_str(), data.as_slice()))?;
        }
        db_err!(tx.commit())?;
        Ok(true)
    }
    /// Explicitly remove one phrase; other study tables are untouched.
    pub fn remove_phrase(&self, id: &str) -> Result<bool, LibraryError> {
        let tx = self.write()?;
        let changed = {
            let mut table = db_err!(tx.open_table(PHRASES))?;
            db_err!(table.remove(id))?.is_some()
        };
        db_err!(tx.commit())?;
        Ok(changed)
    }
}
#[cfg(test)]
mod tests {
    use super::*;
    fn phrase() -> Phrase {
        Phrase {
            id: "00000000-0000-4000-8000-000000000001".into(),
            language: "ja".into(),
            text: "猫が好き".into(),
            definition: "like cats".into(),
            context: "私は猫が好きです。".into(),
            status: WordStatus::Unknown,
            source: None,
            created_ms: 1,
            changed_ms: 1,
        }
    }
    // T-PHR-001, T-PHR-003: real database persistence, duplicate refusal and isolated status/edit/delete.
    #[test]
    fn phrase_records_persist_without_constituent_word_changes() {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("library.redb");
        let lib = Library::open(&path).unwrap();
        let mut p = phrase();
        assert!(lib.phrases().unwrap().is_empty());
        assert!(lib.put_phrase(&p).unwrap());
        let mut duplicate = p.clone();
        duplicate.id = "00000000-0000-4000-8000-000000000002".into();
        assert!(!lib.put_phrase(&duplicate).unwrap());
        p.status = WordStatus::Known;
        p.changed_ms = 2;
        assert!(lib.put_phrase(&p).unwrap());
        assert_eq!(lib.phrases().unwrap(), vec![p.clone()]);
        drop(lib);
        let lib = Library::open(&path).unwrap();
        assert_eq!(lib.phrases().unwrap(), vec![p.clone()]);
        assert!(lib.word_statuses().unwrap().is_empty());
        assert!(lib.remove_phrase(&p.id).unwrap());
        assert!(lib.phrases().unwrap().is_empty());
    }
    // T-PHR-002: a newer schema stays byte-for-byte intact when writes are requested.
    #[test]
    fn readonly_phrase_table_is_readable_but_cannot_be_mutated() {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("newer.redb");
        let lib = Library::open_with(&path, crate::db::SCHEMA_VERSION + 1, &[]).unwrap();
        assert!(lib.put_phrase(&phrase()).unwrap());
        drop(lib);
        let before = std::fs::read(&path).unwrap();
        let lib = Library::open(&path).unwrap();
        assert!(lib.read_only());
        assert_eq!(lib.phrases().unwrap(), vec![phrase()]);
        assert!(lib.put_phrase(&phrase()).is_err());
        assert!(lib.remove_phrase(&phrase().id).is_err());
        drop(lib);
        assert_eq!(std::fs::read(path).unwrap(), before);
    }
    // T-PHR-001: malformed/oversized phrases and nonliteral context never reach the table.
    #[test]
    fn phrase_validation_rejects_invalid_context_and_limits() {
        let p = phrase();
        assert!(p.valid());
        for bad in [
            Phrase {
                text: "犬".into(),
                ..p.clone()
            },
            Phrase {
                definition: "x".repeat(4097),
                ..p.clone()
            },
            Phrase {
                context: "x".repeat(16385),
                ..p.clone()
            },
            Phrase {
                language: "../ja".into(),
                ..p.clone()
            },
            Phrase {
                text: "猫\n犬".into(),
                ..p.clone()
            },
            Phrase {
                changed_ms: 0,
                ..p.clone()
            },
        ] {
            assert!(!bad.valid());
        }
    }
}
