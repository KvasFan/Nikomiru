//! Reader annotations (RDR-001, RDR-002): named bookmarks, highlights and notes
//! over original book locations, in an additive table of their own. They never
//! write word-status, phrase, progress or review tables.

use redb::{ReadableTable, TableDefinition};
use serde::{Deserialize, Serialize};

use crate::{Library, LibraryError, db::db_err};

const ANNOTATIONS: TableDefinition<&str, &[u8]> = TableDefinition::new("annotations");
/// Maximum retained annotations.
pub const MAX_RECORDS: usize = 10_000;
/// Combined text budget of every annotation.
pub const MAX_BYTES: usize = 16 << 20;
/// Longest quoted text.
pub const MAX_QUOTE: usize = 4096;
/// Longest name.
pub const MAX_NAME: usize = 256;
/// Longest note.
pub const MAX_NOTE: usize = 16384;

/// What an annotation is.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
pub enum Kind {
    /// A named place to come back to.
    Bookmark,
    /// Marked text.
    Highlight,
    /// Marked text with a note.
    Note,
}

impl Kind {
    /// Stable name for exports and the harness.
    pub fn name(self) -> &'static str {
        match self {
            Kind::Bookmark => "bookmark",
            Kind::Highlight => "highlight",
            Kind::Note => "note",
        }
    }

    /// From [`Kind::name`].
    pub fn from_name(name: &str) -> Option<Self> {
        [Kind::Bookmark, Kind::Highlight, Kind::Note]
            .into_iter()
            .find(|k| k.name() == name)
    }
}

/// One annotation over an original reader location.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Annotation {
    /// Stable UUID generated by the application.
    pub id: String,
    /// What it is.
    pub kind: Kind,
    /// The book's library identity.
    pub book: String,
    /// The book's title when it was made.
    pub title: String,
    /// Original chapter.
    pub chapter: u32,
    /// Original paragraph.
    pub paragraph: u32,
    /// Original UTF-8 byte range in the paragraph.
    pub start: u32,
    /// End of that range.
    pub end: u32,
    /// The exact original text of that range.
    pub quote: String,
    /// The learner's name for it; required for bookmarks.
    pub name: String,
    /// The learner's note.
    pub note: String,
    /// Creation time, Unix ms.
    pub created_ms: i64,
    /// Last edit, Unix ms.
    pub changed_ms: i64,
}

fn uuid_valid(id: &str) -> bool {
    let id = id.as_bytes();
    id.len() == 36
        && id.iter().enumerate().all(|(i, c)| {
            if [8, 13, 18, 23].contains(&i) {
                *c == b'-'
            } else {
                c.is_ascii_hexdigit()
            }
        })
}

fn plain(text: &str, limit: usize, multiline: bool) -> bool {
    text.len() <= limit
        && !text
            .chars()
            .any(|c| c.is_control() && (!multiline || !matches!(c, '\n' | '\r' | '\t')))
}

impl Annotation {
    /// Bounds, a non-empty quoted range of matching length and kind rules.
    pub fn valid(&self) -> bool {
        uuid_valid(&self.id)
            && !self.book.is_empty()
            && plain(&self.book, 1024, false)
            && plain(&self.title, 1024, false)
            && self.end > self.start
            && (self.end - self.start) as usize == self.quote.len()
            && !self.quote.is_empty()
            && self.quote.len() <= MAX_QUOTE
            && plain(&self.quote, MAX_QUOTE, true)
            && plain(&self.name, MAX_NAME, false)
            && plain(&self.note, MAX_NOTE, true)
            && (self.kind != Kind::Bookmark || !self.name.trim().is_empty())
            && self.created_ms >= 0
            && self.changed_ms >= self.created_ms
    }

    /// Whether `text`, the paragraph it now points to, still holds its quote.
    pub fn current_in(&self, text: &str) -> bool {
        text.get(self.start as usize..self.end as usize) == Some(self.quote.as_str())
    }

    fn bytes(&self) -> usize {
        self.book.len() + self.title.len() + self.quote.len() + self.name.len() + self.note.len()
    }

    fn duplicates(&self, other: &Self) -> bool {
        (
            self.kind,
            &self.book,
            self.chapter,
            self.paragraph,
            self.start,
            self.end,
            &self.name,
            &self.note,
        ) == (
            other.kind,
            &other.book,
            other.chapter,
            other.paragraph,
            other.start,
            other.end,
            &other.name,
            &other.note,
        )
    }

    /// Reading order within a book.
    pub fn place(&self) -> (u32, u32, u32, u32) {
        (self.chapter, self.paragraph, self.start, self.end)
    }
}

impl Library {
    /// Every annotation, by book then reading order; an absent table is empty.
    pub fn annotations(&self) -> Result<Vec<Annotation>, LibraryError> {
        self.read(|tx| {
            let table = match tx.open_table(ANNOTATIONS) {
                Ok(t) => t,
                Err(redb::TableError::TableDoesNotExist(_)) => return Ok(Vec::new()),
                Err(e) => return Err(LibraryError::Db(e.into())),
            };
            let mut rows = Vec::new();
            let mut bytes = 0usize;
            for row in db_err!(table.iter())? {
                let (_, value) = db_err!(row)?;
                let a: Annotation = postcard::from_bytes(value.value())?;
                bytes += a.bytes();
                if !a.valid() || rows.len() >= MAX_RECORDS || bytes > MAX_BYTES {
                    return Err(LibraryError::Record(postcard::Error::SerdeDeCustom));
                }
                rows.push(a);
            }
            rows.sort_by(|a, b| (&a.book, a.place(), &a.id).cmp(&(&b.book, b.place(), &b.id)));
            Ok(rows)
        })
    }

    /// Atomically save one validated annotation; duplicates and overflow are refused.
    pub fn put_annotation(&self, annotation: &Annotation) -> Result<bool, LibraryError> {
        if !annotation.valid() {
            return Ok(false);
        }
        let tx = self.write()?;
        {
            let mut table = db_err!(tx.open_table(ANNOTATIONS))?;
            let mut count = 0usize;
            let mut bytes = annotation.bytes();
            for row in db_err!(table.iter())? {
                let (key, value) = db_err!(row)?;
                if key.value() == annotation.id {
                    continue;
                }
                let other: Annotation = postcard::from_bytes(value.value())?;
                if other.duplicates(annotation) {
                    return Ok(false);
                }
                count += 1;
                bytes = bytes.saturating_add(other.bytes());
            }
            if count >= MAX_RECORDS || bytes > MAX_BYTES {
                return Ok(false);
            }
            let data = postcard::to_stdvec(annotation)?;
            db_err!(table.insert(annotation.id.as_str(), data.as_slice()))?;
        }
        db_err!(tx.commit())?;
        Ok(true)
    }

    /// Explicitly remove one annotation.
    pub fn remove_annotation(&self, id: &str) -> Result<bool, LibraryError> {
        let tx = self.write()?;
        let changed = {
            let mut table = db_err!(tx.open_table(ANNOTATIONS))?;
            db_err!(table.remove(id))?.is_some()
        };
        db_err!(tx.commit())?;
        Ok(changed)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    pub(crate) fn note() -> Annotation {
        Annotation {
            id: "00000000-0000-4000-8000-000000000001".into(),
            kind: Kind::Note,
            book: "book/abc".into(),
            title: "猫".into(),
            chapter: 1,
            paragraph: 2,
            start: 6,
            end: 12,
            quote: "猫が".into(),
            name: String::new(),
            note: "cats\nlike".into(),
            created_ms: 1,
            changed_ms: 1,
        }
    }

    // T-RDR-001: real database persistence, duplicate refusal, edits, deletion and isolation.
    #[test]
    fn annotations_persist_without_touching_other_tables() {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("library.redb");
        let lib = Library::open(&path).unwrap();
        assert!(lib.annotations().unwrap().is_empty());
        let mut a = note();
        assert!(lib.put_annotation(&a).unwrap());
        let mut copy = a.clone();
        copy.id = "00000000-0000-4000-8000-000000000002".into();
        assert!(!lib.put_annotation(&copy).unwrap(), "exact duplicate");
        copy.note = "other".into();
        assert!(lib.put_annotation(&copy).unwrap(), "another note there");
        a.note = "edited".into();
        a.changed_ms = 5;
        assert!(lib.put_annotation(&a).unwrap(), "an edit replaces itself");
        let mut bookmark = note();
        bookmark.id = "00000000-0000-4000-8000-000000000003".into();
        bookmark.kind = Kind::Bookmark;
        bookmark.name = "start".into();
        bookmark.chapter = 0;
        assert!(lib.put_annotation(&bookmark).unwrap());
        let rows = lib.annotations().unwrap();
        assert_eq!(rows.len(), 3);
        assert_eq!(rows[0], bookmark, "reading order");
        drop(lib);
        let lib = Library::open(&path).unwrap();
        assert_eq!(lib.annotations().unwrap().len(), 3);
        assert!(lib.word_statuses().unwrap().is_empty());
        assert!(lib.phrases().unwrap().is_empty());
        assert!(lib.books().unwrap().is_empty());
        assert!(lib.remove_annotation(&a.id).unwrap());
        assert!(!lib.remove_annotation(&a.id).unwrap());
        assert_eq!(lib.annotations().unwrap().len(), 2);
    }

    // T-RDR-001: invalid records never reach the table.
    #[test]
    fn annotation_validation_rejects_bad_ranges_and_text() {
        let a = note();
        assert!(a.valid());
        for bad in [
            Annotation {
                end: 6,
                ..a.clone()
            },
            Annotation {
                end: 13,
                ..a.clone()
            },
            Annotation {
                kind: Kind::Bookmark,
                ..a.clone()
            },
            Annotation {
                name: "a\u{7}".into(),
                ..a.clone()
            },
            Annotation {
                name: "x".repeat(MAX_NAME + 1),
                ..a.clone()
            },
            Annotation {
                note: "x".repeat(MAX_NOTE + 1),
                ..a.clone()
            },
            Annotation {
                id: "x".into(),
                ..a.clone()
            },
            Annotation {
                changed_ms: 0,
                ..a.clone()
            },
        ] {
            assert!(!bad.valid(), "{bad:?}");
        }
        let dir = tempfile::tempdir().unwrap();
        let lib = Library::open(&dir.path().join("l.redb")).unwrap();
        assert!(!lib.put_annotation(&Annotation { end: 6, ..a }).unwrap());
        assert!(lib.annotations().unwrap().is_empty());
    }

    // T-RDR-002: a changed paragraph makes an annotation stale.
    #[test]
    fn current_only_where_the_quote_still_is() {
        let a = note();
        assert!(a.current_in("私は猫が好き"));
        assert!(!a.current_in("私は犬が好き"), "the text under it changed");
        assert!(!a.current_in("私は"), "the paragraph got shorter");
        assert!(!a.current_in("私\u{e9}猫が好き"), "not on a char boundary");
    }

    // T-RDR-001: a newer schema is readable and never mutated.
    #[test]
    fn readonly_annotations_cannot_be_mutated() {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("newer.redb");
        let lib = Library::open_with(&path, crate::db::SCHEMA_VERSION + 1, &[]).unwrap();
        assert!(lib.put_annotation(&note()).unwrap());
        drop(lib);
        let before = std::fs::read(&path).unwrap();
        let lib = Library::open(&path).unwrap();
        assert!(lib.read_only());
        assert_eq!(lib.annotations().unwrap(), vec![note()]);
        assert!(lib.put_annotation(&note()).is_err());
        assert!(lib.remove_annotation(&note().id).is_err());
        drop(lib);
        assert_eq!(std::fs::read(path).unwrap(), before);
    }
}
